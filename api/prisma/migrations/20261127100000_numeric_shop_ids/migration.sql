WITH sample_names AS (
    SELECT ARRAY['佐藤', '鈴木', '高橋', '田中', '伊藤', '渡辺', '山本', '中村', '小林', '加藤', '吉田', '山田', '佐々木', '山口', '松本', '井上', '木村', '林', '清水', '池田', '橋本', '阿部', '森', '石川'] AS family_names,
           ARRAY['葵', '陽菜', '蓮', '大翔', '美咲', '結衣', '陽翔', '優斗', '美月', '蒼', 'まどか', '凛', '美穂', '悠真', '直樹', '遥', '和也', '恵', '翔太', '楓', '陸', '海斗', '沙織', '紗季', '健太'] AS given_names
), sample_customer AS (
    SELECT "id", substring("email" from '^large-seed-([0-9]{1,3})@example[.]test$')::integer AS seed_index
    FROM "Customer"
    WHERE "lastName" = '演習用顧客'
)
UPDATE "Customer" AS customer
SET "lastName" = (family_names)[seed_index % cardinality(family_names) + 1],
    "firstName" = (given_names)[seed_index / cardinality(family_names) % cardinality(given_names) + 1]
FROM sample_customer, sample_names
WHERE customer."id" = sample_customer."id"
  AND sample_customer.seed_index BETWEEN 0 AND 599
  AND customer."firstName" = (sample_customer.seed_index + 1)::text;

